package Aula;

public class Pessoas {
	int idPessoa;
	String nome;
	
	
	public void setIdPessoa(int _id) {
		this.idPessoa = _id;
			
	}
	
	public void setNome(String _nome) {
		this.nome = _nome;
	}
	
	public int getIdPessoa(){
		return this.idPessoa;		
	}

	public String getNome() {
		return this.nome;
	}
}
